import assert from "node:assert/strict";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const base = process.env.TEST_BASE_URL || "http://127.0.0.1:4321/Blog/";
const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || "msedge", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  await page.bringToFront();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base, { waitUntil: 'domcontentloaded' });
  await page.waitForFunction(() => document.documentElement.dataset.motion === 'on');
  await page.mouse.move(700, 400);
  await page.waitForTimeout(400);
  assert.equal(await page.locator('#cursor-halo').evaluate(e => getComputedStyle(e).opacity), '1');
  await page.mouse.click(700, 400);
  assert(await page.locator('.click-ripple').count());
  await page.locator('#motion-toggle').click();
  assert.equal(await page.locator('html').getAttribute('data-motion'), 'off');
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.waitForFunction(() => document.documentElement.dataset.motion === 'off');
  await page.locator('#motion-toggle').click();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.waitForFunction(() => document.documentElement.dataset.motion === 'off');
  assert(await page.locator('#motion-toggle').isDisabled());
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.waitForFunction(() => document.documentElement.dataset.motion === 'on');
  await page.locator('#home-intro').scrollIntoViewIfNeeded();
  await page.waitForTimeout(600);
  assert.equal(await page.locator('[data-glow-card]').count(), 3);
  if (process.env.SCREENSHOT_PATH) await page.screenshot({ path: process.env.SCREENSHOT_PATH });
  console.log('Desktop: cursor, ripple, persisted toggle, reduced motion, three cards PASS');
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  await mobile.goto(base, { waitUntil: 'domcontentloaded' });
  assert.equal(await mobile.locator('#ambient-field').evaluate(e => getComputedStyle(e).display), 'none');
  assert(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  console.log('Mobile: decorative canvas disabled, no horizontal overflow PASS');
  assert.deepEqual(errors, [], 'Unexpected client errors');
} finally { await browser.close(); }
